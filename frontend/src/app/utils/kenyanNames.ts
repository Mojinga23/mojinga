/**
 * Generates an authentic Kenyan name for any phone number with uniform dispersion.
 */
export function generateKenyanName(phoneNumber: string): string {
  let p = (phoneNumber || '').replace(/\D/g, '');
  if (p.length === 12 && p.startsWith('254')) {
    p = '0' + p.slice(3);
  }
  if (p.length !== 10 || (!p.startsWith('07') && !p.startsWith('01'))) {
    return '';
  }

  // FNV-1a 32-bit hash with prime multipliers for uniform non-repeating dispersion
  let hash = 0x811c9dc5;
  for (let i = 0; i < p.length; i++) {
    hash ^= p.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
    hash ^= (hash >>> 13);
  }

  const index = Math.abs(hash) % KENYAN_NAMES.length;
  return KENYAN_NAMES[index].toUpperCase();
}
